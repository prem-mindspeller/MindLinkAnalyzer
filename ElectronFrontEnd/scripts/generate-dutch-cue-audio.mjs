import { createHash } from 'node:crypto';
import { mkdir, readFile, stat, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { TASK_IDS, taskFormForSession } from '../src/components/tasks/optimizedBatteryConfig.mjs';

const currentDirectory = dirname(fileURLToPath(import.meta.url));
const frontendDirectory = resolve(currentDirectory, '..');
const repositoryDirectory = resolve(frontendDirectory, '..');
const outputDirectory = resolve(frontendDirectory, 'src/assets/audio/dutch-cues');
const assetModulePath = resolve(frontendDirectory, 'src/components/tasks/dutchCueAudioAssets.mjs');
const voiceId = 'SVmtrm5iuquj8zKn5ZMg'; // Will — Dutch-accent European narrator
const modelId = 'eleven_multilingual_v2';
const outputFormat = 'mp3_44100_128';

const env = await readFile(resolve(repositoryDirectory, 'newBackend/.env'), 'utf8');
const apiKey = env.match(/^\s*MDSP_ELEVENLABS_API\s*=\s*(.+?)\s*$/m)?.[1];
if (!apiKey) throw new Error('MDSP_ELEVENLABS_API is missing from newBackend/.env');

const sha256 = (value) => createHash('sha256').update(value).digest('hex');
const audioFileName = (text) => `cue-${sha256(text).slice(0, 16)}.mp3`;
const taskIds = [TASK_IDS.NUMERICAL, TASK_IDS.WORKING_MEMORY, TASK_IDS.DUAL_TASK];
const sessionDepths = ['session_1', 'session_2', 'session_3'];
const cueTexts = [...new Set(taskIds.flatMap((taskId) => sessionDepths.flatMap((sessionDepth) => (
  taskFormForSession(taskId, sessionDepth, undefined, 'nl').spokenEvents.map((event) => event.text)
))))];

async function remainingCharacters() {
  const response = await fetch('https://api.elevenlabs.io/v1/user/subscription', {
    headers: { 'xi-api-key': apiKey },
  });
  if (!response.ok) throw new Error(`ElevenLabs subscription lookup failed (${response.status})`);
  const subscription = await response.json();
  return Number(subscription.character_limit) - Number(subscription.character_count);
}

async function synthesize(text) {
  const response = await fetch(
    `https://api.elevenlabs.io/v1/text-to-speech/${voiceId}?output_format=${outputFormat}`,
    {
      method: 'POST',
      headers: { 'Content-Type': 'application/json', 'xi-api-key': apiKey },
      body: JSON.stringify({
        text,
        model_id: modelId,
        language_code: 'nl',
        voice_settings: {
          stability: 0.7,
          similarity_boost: 0.8,
          style: 0,
          use_speaker_boost: true,
          speed: 1,
        },
      }),
    },
  );
  if (!response.ok) throw new Error(`ElevenLabs synthesis failed (${response.status})`);
  return Buffer.from(await response.arrayBuffer());
}

const requiredCharacters = cueTexts.reduce((total, text) => total + text.length, 0);
const availableCharacters = await remainingCharacters();
if (availableCharacters < requiredCharacters) {
  throw new Error(`ElevenLabs allowance is insufficient: ${availableCharacters} available, ${requiredCharacters} required`);
}

await mkdir(outputDirectory, { recursive: true });
const assets = {};
for (const text of cueTexts) {
  const file = audioFileName(text);
  const path = resolve(outputDirectory, file);
  let audio = await readFile(path).catch(() => null);
  if (audio) {
    console.log(`Reused ${file}`);
  } else {
    audio = await synthesize(text);
    await writeFile(path, audio);
    console.log(`Generated ${file}`);
  }
  const fileInfo = await stat(path);
  assets[text] = {
    file,
    sha256: sha256(audio),
    character_count: text.length,
    byte_length: fileInfo.size,
  };
}

const assetRows = Object.entries(assets).map(([text, asset]) => (
  `  ${JSON.stringify(text)}: asset(new URL('../../assets/audio/dutch-cues/${asset.file}', import.meta.url).href, '${asset.sha256}'),`
));
const assetModule = `// Generated by scripts/generate-dutch-cue-audio.mjs.\nconst asset = (uri, sha256) => Object.freeze({\n  uri,\n  sha256,\n  provider: 'elevenlabs',\n  modelId: 'eleven_multilingual_v2',\n  outputFormat: 'mp3_44100_128',\n  voiceLabel: 'Will - Dutch-accent European narrator',\n});\n\nconst ASSET_BY_TEXT = Object.freeze({\n${assetRows.join('\n')}\n});\n\nexport function dutchCueAudioAssetsForForm(form) {\n  return Object.fromEntries((form?.spokenEvents || []).flatMap((event, index) => {\n    const configured = ASSET_BY_TEXT[event.text];\n    return configured ? [[\`${'${form.id}'}:speech:${'${index}'}\`, { ...configured, playbackRate: 0.8 }]] : [];\n  }));\n}\n\nexport function dutchCueAudioAssetCount() {\n  return Object.keys(ASSET_BY_TEXT).length;\n}\n`;

await writeFile(assetModulePath, assetModule, 'utf8');
await writeFile(resolve(outputDirectory, 'manifest.json'), `${JSON.stringify({
  version: 'dutch_cue_audio_candidate.2',
  provider: 'elevenlabs',
  model_id: modelId,
  voice_id: voiceId,
  voice_label: 'Will - Dutch-accent European narrator',
  output_format: outputFormat,
  assets,
}, null, 2)}\n`, 'utf8');
